package control_flow;
import java.util.*;
public class Question5 {
	 public static void main(String[] args) {
		 Scanner sc = new Scanner(System.in);
	        int counter = sc.nextInt();
	        while (counter >= 1) {
	            System.out.println(counter);
	            counter--;
	        }
	        sc.close();
	    }
}
